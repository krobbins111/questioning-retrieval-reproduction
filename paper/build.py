def _count_errors(split: str) -> dict:
    """The summed calibrated match probabilities against the true number of relevant photos among the 500 checked."""
    import importlib
    nb = {}

    def geo(S, w):
        S = np.clip(np.nan_to_num(S, nan=.5), .02, 1)
        return np.exp((np.log(S) * w).sum(1) / w.sum())

    def lg(p):
        p = np.clip(p, .02, .98)
        return np.log(p / (1 - p))

    def feats(src):
        Q, P = load(src)
        X, Y, tot = [], [], []
        for q in sorted(P):
            ph = sorted(P[q], key=lambda p: p.search_rank)[:500]
            S = np.array([[np.nan if x is None else x for x in p.s] for p in ph], float)
            h = np.array([.5 if p.h is None else p.h for p in ph]); r = np.array([.5 if p.r is None else p.r for p in ph])
            X.append(np.c_[lg(h), lg(geo(S, np.array(ph[0].w))), r]); Y.append(np.array([p.image_id in relevant(Q[q]) for p in ph]))
        return X, Y
    Xv, Yv = feats("inquire_full_vith_lc_val")
    X = np.concatenate(Xv); y = np.concatenate(Yv).astype(float)
    mu, sd = X.mean(0), X.std(0) + 1e-9
    A = np.c_[(X - mu) / sd, np.ones(len(X))]; w = np.zeros(A.shape[1])
    for _ in range(80):
        p = 1 / (1 + np.exp(-np.clip(A @ w, -30, 30)))
        g = A.T @ (p - y) / len(y) + 1e-3 * w
        H = (A * (p * (1 - p))[:, None]).T @ A / len(y) + 1e-3 * np.eye(A.shape[1])
        stp = np.linalg.solve(H, g); w -= stp
        if np.abs(stp).max() < 1e-8:
            break
    Xs, Ys = feats(f"inquire_full_vith_lc_{split}")
    pred = np.array([(1 / (1 + np.exp(-np.clip(np.c_[(x - mu) / sd, np.ones(len(x))] @ w, -30, 30)))).sum() for x in Xs])
    true = np.array([yy.sum() for yy in Ys], float)
    return dict(mae=float(np.abs(pred - true).mean()), mean=float(true.mean()),
                w25=float(np.mean(np.abs(pred - true) <= 0.25 * true)), x2=float(np.mean((pred <= 2 * true) & (pred >= true / 2))))


