# ------------------------------------------------------------------------------------------------------- helpers
def _signed(v, nd=1):
    t = f"{v:+.{nd}f}"
    return t[1:] if float(t) == 0 else t                      # no "-0.0"


def f(x, nd=1, pct=False, dash="--", sign=False):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return dash
    v = 100 * x if pct else x
    return _signed(v, nd) if sign else f"{v:.{nd}f}"


def ci(m, lo, hi, nd=1):
    return f"{_signed(m, nd)} ({_signed(lo, nd)} to {_signed(hi, nd)})"


def write_table(name: str, body: str, caption: str, star: bool = False, size: str = "\\small") -> None:
    env = "table*" if star else "table"
    size = size if star else size + "\\setlength{\\tabcolsep}{4pt}"
    tex = (f"% generated by paper/build.py ({name}); do not edit by hand\n\\begin{{{env}}}[!htbp]\n\\centering\n{size}\n"
           f"\\caption{{{caption}}}\n\\label{{tab:supp_{name}}}\n{body}\n\\end{{{env}}}\n")
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "tables" / f"{name}.tex").write_text(tex, encoding="utf-8")
    print(f"  wrote tables/{name}.tex")


MINUS = re.compile(r"(?<![-\w$])-(?=\d)")                  # a minus sign, not a hyphen, before a number in a cell


def tabular(colspec: str, header: list[str], rows: list, groups: dict | None = None) -> str:
    """rows: list of lists of cells, or a string (a full LaTeX line such as \\midrule)."""
    out = ["\\begin{adjustbox}{max width=\\linewidth}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule"] + header + ["\\midrule"]
    for r in rows:
        out.append(r if isinstance(r, str) else " & ".join(MINUS.sub("$-$", c) for c in r) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}"]
    return "\n".join(out)


def search_order(photos):
    return [p.image_id for p in sorted(photos, key=lambda p: (-p.search_score, p.search_rank))]


def ranked(photos, rule="paper", mode="weighted", keep=None):
    if keep is not None:
        photos = [replace(p, s=p.s[:keep], w=p.w[:keep]) for p in photos]
    w, a = N.RULES[rule]
    return [p.image_id for p, _ in rank(photos, a, w, mode)]


def ndcg_at(ids, rel, k):
    dcg = sum(1.0 / math.log2(i + 2) for i, x in enumerate(ids[:k]) if x in rel)
    idcg = sum(1.0 / math.log2(i + 2) for i in range(min(len(rel), k)))
    return dcg / idcg if idcg else 0.0


def mrr_at(ids, rel, k):
    return next((1.0 / (i + 1) for i, x in enumerate(ids[:k]) if x in rel), 0.0)


