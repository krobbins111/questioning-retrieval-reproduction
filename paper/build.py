    assert abs(MT[:, 0].mean() - check) < 1e-12, "vectorised score differs from qr.score"
    d = boot_ci(100 * (MT[:, 1] - MT[:, 0]))
    vals["rerank"] = dict(fitted=WF_GRID[g], val_hand=MV[:, hand].mean(), val_fit=MV[:, g].mean(), hand=MT[:, 0].mean(), fit=MT[:, 1].mean(), ci=d)
    rows.append(["INQUIRE-Rerank, AP", "validation (40)", f(MT[:, 0].mean(), pct=True), f(MT[:, 1].mean(), pct=True), ci(*d)])
    # INQUIRE-Fullrank, each pool with its own search score, 100 and 500 photos, mAP@50
    for pool, pname in (("vith_lc", "ViT-H"), ("siglip2_lc", "SigLIP2")):
        Qv, Pv = load(f"inquire_full_{pool}_val"); Qt, Pt = load(f"inquire_full_{pool}_test")
        for k in (100, 500):
            sub = lambda P, q: [p for p in P[q] if p.search_rank <= k]  # noqa: E731
            MV = np.array([_wf_ap(_wf_arrays(sub(Pv, q)), [p.image_id for p in sub(Pv, q)], relevant(Qv[q]), 50, WF_GRID) for q in sorted(Pv)])
