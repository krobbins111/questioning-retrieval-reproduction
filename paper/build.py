def release() -> None:
    """Sec. S1's count of the release, from the data folder's manifest (the file scripts/fetch_data.py checks):
    \\releasestats in paper/out/tables/release.tex. Answers are counted as the dataset card counts them."""
    man = json.loads((data_root() / "manifest.json").read_text(encoding="utf-8"))
    files = [x for v in man.values() for x in v]
    answers = sum(x["rows"] for x in files if Path(x["file"]).stem == "answers")
    mb = sum(x["bytes"] for x in files) / 1e6
    VALUES["release"] = dict(answers=answers, files=len(files), mb=mb)
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "tables/release.tex").write_text(
        f"\\newcommand{{\\releasestats}}{{{answers / 1e6:.1f} million answers in {len(files)} parquet tables ({mb:.0f}\\,MB)}}\n", encoding="utf-8")
    print(f"  release: {answers:,} answers, {len(files)} files, {mb:.1f} MB")


