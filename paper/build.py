def next_batch() -> None:
    """Eq. 3, fitted on the 50 validation queries and used on the 200 test queries (ViT-H pool), and the allocation of
    a shared budget by its first input."""
    def geo(S, w):
        S = np.clip(np.nan_to_num(S, nan=.5), .02, 1)
        return np.exp((np.log(S) * w).sum(1) / w.sum())

    def lg(p):
        p = np.clip(p, .02, .98)
        return np.log(p / (1 - p))

    def logreg(X, y, l2=1e-3):
        X = np.asarray(X, float); y = np.asarray(y, float)
        mu, sd = X.mean(0), X.std(0) + 1e-9
        A = np.c_[(X - mu) / sd, np.ones(len(X))]; w = np.zeros(A.shape[1])
        for _ in range(80):
            p = 1 / (1 + np.exp(-np.clip(A @ w, -30, 30)))
            g = A.T @ (p - y) / len(y) + l2 * w
            H = (A * (p * (1 - p))[:, None]).T @ A / len(y) + l2 * np.eye(A.shape[1])
            stp = np.linalg.solve(H, g); w -= stp
            if np.abs(stp).max() < 1e-8:
                break
        return (lambda Z: 1 / (1 + np.exp(-np.clip(np.c_[(np.asarray(Z, float) - mu) / sd, np.ones(len(Z))] @ w, -30, 30)))), w

    def queries(split):
        src = f"inquire_full_vith_lc_{split}"
        Q, P = load(src)
        fs = defaultdict(list)
        for r in pq.read_table(data_root() / src / "firststage.parquet").to_pylist():
            fs[r["query_id"]].append(r)
        L5 = defaultdict(dict)
        for r in pq.read_table(data_root() / src / "answers.parquet", columns=["query_id", "image_id", "question_id", "p_levels"]).to_pylist():
            if r["question_id"] == "relevance" and r["p_levels"]:
                L5[r["query_id"]][r["image_id"]] = int(np.argmax(r["p_levels"]) == 4)
        out = []
        for q in sorted(P):
            ids = [r["image_id"] for r in sorted(fs[q], key=lambda r: r["rank"])][:1000]
            by = {p.image_id: p for p in P[q]}
            ph = [by[i] for i in ids[:500]]
            S = np.array([[np.nan if x is None else x for x in p.s] for p in ph], float)
            out.append(dict(qid=q, y=np.array([i in relevant(Q[q]) for i in ids]), h=np.array([.5 if p.h is None else p.h for p in ph]),
                            r=np.array([.5 if p.r is None else p.r for p in ph]), s=geo(S, np.array(ph[0].w)),
                            L5=np.array([L5[q].get(p.image_id, 0) for p in ph], bool), nrel=len(relevant(Q[q])), n=len(ids)))
        return out

    V, T = queries("val"), queries("test")
    cal, cw = logreg(np.concatenate([np.c_[lg(q["h"]), lg(q["s"]), q["r"]] for q in V]), np.concatenate([q["y"][:500] for q in V]))
    for q in V + T:
        q["p"] = cal(np.c_[lg(q["h"]), lg(q["s"]), q["r"]])

    def rows_of(Qs):
        X, Y, D_ = [], [], []
        for q in Qs:
            for D in (100, 200, 300, 400, 500):
                if q["n"] < D + 100:
                    continue
                a, b = D - 100, D
                X.append([q["p"][a:b].sum(), q["L5"][a:b].mean(), q["h"][a:b].mean(), D / 100.0]); Y.append(bool(q["y"][D:D + 100].any())); D_.append(D)
        return np.array(X), np.array(Y), np.array(D_)
    Xv, yv, _ = rows_of(V); Xt, yt, Dt = rows_of(T)
    model, w = logreg(Xv, yv, l2=1e-2)
    Pt = model(Xt)
    by_depth = {int(D): auroc(Pt[Dt == D], yt[Dt == D]) for D in (100, 200, 300, 400, 500)}
    bins = []
    for lo, hi in ((.2, .4), (.4, .6), (.6, .8), (.8, .95), (.95, 1.01)):
        m = (Pt >= lo) & (Pt < hi)
        bins.append((lo, hi, int(m.sum()), float(yt[m].mean()) if m.any() else float("nan")))
    # allocation of a shared budget: the next 100 photos go to the query with the most expected matches in its last 100
    uni = {}
    alloc = {}
    for B in (200, 300, 400):
        uni[B] = (np.mean([q["y"][:B].sum() / max(1, q["nrel"]) for q in T]), np.mean([q["y"][:B].sum() for q in T]))
        D = {i: 100 for i in range(len(T))}
        total = int(round((B - 100) / 100 * len(T)))
        heap = [(-T[i]["p"][0:100].sum(), i) for i in range(len(T))]
        heapq.heapify(heap)
        for _ in range(total):
            if not heap:
                break
            _, i = heapq.heappop(heap); D[i] += 100
            if D[i] < 600:
                heapq.heappush(heap, (-T[i]["p"][D[i] - 100:D[i]].sum(), i))
        alloc[B] = (np.mean([T[i]["y"][:D[i]].sum() / max(1, T[i]["nrel"]) for i in D]), np.mean([T[i]["y"][:D[i]].sum() for i in D]))
    names = ["Expected matches $m$", "Share rated 5, $e$", "Mean whole-query $P(\\mathrm{yes})$, $\\bar h$", "Photos checked (hundreds)", "Intercept"]
    VALUES["next_batch"] = dict(coef=[float(x) for x in w], auroc=float(auroc(Pt, yt)), by_depth=by_depth, bins=bins,
                                uniform={str(k): [float(a), float(b)] for k, (a, b) in uni.items()}, alloc={str(k): [float(a), float(b)] for k, (a, b) in alloc.items()},
                                cal_coef=[float(x) for x in cw])
    rows = [[n, f(x, 2)] for n, x in zip(names, w)]
    rows += ["\\midrule", ["AUROC, all depths (1{,}000 points)", f(auroc(Pt, yt), 2)]]
    rows += [[f"\\quad after {D} photos", f(a, 2)] for D, a in by_depth.items()]
    rows += ["\\midrule"] + [[f"Predicted {100 * lo:.0f}--{min(100, 100 * hi):.0f}\\%: observed ({n} batches)", f(r, 0, pct=True)] for lo, hi, n, r in bins]
    write_table("next_batch", tabular("lc", ["& Value \\\\"], rows),
                "The next-batch predictor (Eq. 3) on INQUIRE-Fullrank, CLIP ViT-H pool: a logistic regression fitted on the "
                "50 validation queries (inputs standardized; coefficients shown) and applied unchanged to the 200 test queries. "
                "Besides the three answers of Eq. 3, the fitted model takes the number of photos already checked as input.")
    rows = []
    for B in (200, 300, 400):
        (fu, mu), (fa, ma) = uni[B], alloc[B]
        rows.append([str(B), f(fu, pct=True), f(mu, 1), f(fa, pct=True), f(ma, 1), f(100 * (fa - fu), 1, sign=True), f(100 * (ma / mu - 1), 0, sign=True)])
    write_table("allocation", tabular("lcccccc", ["& \\multicolumn{2}{c}{Same photos per query} & \\multicolumn{2}{c}{Allocated by $m$} & \\multicolumn{2}{c}{Change} \\\\",
                                                 "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
                                                 "Photos per query (mean) & Found (\\%) & Matches & Found (\\%) & Matches & Found (points) & Matches (\\%) \\\\"], rows),
                "Sharing a verification budget across the 200 INQUIRE-Fullrank test queries: every query gets its first 100 "
                "photos, then each further batch of 100 goes to the query with the most expected matches in its last batch. "
                "``Found'' is the mean share of each query's relevant photos inside its checked set.", star=True, size="\\footnotesize")
    reliability(T, V)


