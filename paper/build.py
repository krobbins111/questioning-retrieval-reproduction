def metrics() -> None:
    """INQUIRE's other metrics next to AP: nDCG and MRR over the same cutoff (100 for Rerank, 50 for Fullrank)."""
    rows, vals = [], {}
    Q, P = load("inquire_rerank_test")
    for name, order in (("Search", search_order), ("Jev + search", ranked)):
        ids = {q: order(P[q]) for q in P}
        m = [np.mean([fn(ids[q], relevant(Q[q]), 100) for q in P]) for fn in (ap_at, ndcg_at, mrr_at)]
        vals[f"rerank.{name}"] = [float(x) for x in m]
        rows.append([f"INQUIRE-Rerank, {name.lower()}", "100"] + [f(x, pct=True) for x in m])
    rows.append("\\midrule")
    for pool, pname in (("vith_lc", "CLIP ViT-H"), ("siglip2_lc", "SigLIP2")):
        Q, P = load(f"inquire_full_{pool}_test")
        for name, k in (("search", None), ("Jev, 100", 100), ("Jev, 500", 500)):
            ids = {q: (search_order(P[q]) if k is None else ranked([p for p in P[q] if p.search_rank <= k])) for q in sorted(P)}
            m = [np.mean([fn(ids[q], relevant(Q[q]), 50) for q in sorted(P)]) for fn in (ap_at, ndcg_at, mrr_at)]
            vals[f"full.{pool}.{name}"] = [float(x) for x in m]
            rows.append([f"Fullrank, {pname} pool, {name}", "50"] + [f(x, pct=True) for x in m])
    VALUES["metrics"] = vals
    write_table("metrics", tabular("lcccc", ["Setting & Cutoff & AP & nDCG & MRR \\\\"], rows),
                "INQUIRE's three metrics on the test queries. nDCG counts every relevant photo outside the cutoff as ranked "
                "last, as INQUIRE's scorer does; MRR looks at the cutoff only.")


