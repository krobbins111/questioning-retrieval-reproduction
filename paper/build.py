def rerank() -> None:
    """INQUIRE-Rerank: AP over the 100 photos, test, Divide and Conquer's 154 queries, validation."""
    C = defaultdict(dict)
    for c in pq.read_table(data_root() / "inquire_rerank_test/candidates.parquet").to_pylist():
        C[c["query_id"]][c["image_id"]] = c["siglip2_score"]
    Q, P = load("inquire_rerank_test")
    Qc, Pc = load("inquire_rerank_test", answers_dir="clef_flash")
    Qv, Pv = load("inquire_rerank_val")
    dc = [q for q in P if meta(Q[q]).get("supercategory") != "Species"]

    def mean_ap(Qs, Ps, order, qs):
        return float(np.mean([ap_at(order(Ps[q], q), relevant(Qs[q]), 100) for q in qs]))

    as_written = lambda ph, q: sorted((p.image_id for p in ph), key=lambda i: -C[q][i])  # noqa: E731
    rows = {
        "SigLIP2, as written": (mean_ap(Q, P, as_written, P), mean_ap(Q, P, as_written, dc), mean_ap(Qv, Pv, lambda ph, q: search_order(ph), Pv)),
        "SigLIP2, lowercased": (mean_ap(Q, P, lambda ph, q: search_order(ph), P), mean_ap(Q, P, lambda ph, q: search_order(ph), dc), None),
        "Jev + SigLIP2": (mean_ap(Q, P, lambda ph, q: ranked(ph), P), mean_ap(Q, P, lambda ph, q: ranked(ph), dc),
                                           mean_ap(Qv, Pv, lambda ph, q: ranked(ph), Pv)),
        "Clef-Flash + SigLIP2": (mean_ap(Qc, Pc, lambda ph, q: ranked(ph), Pc), mean_ap(Qc, Pc, lambda ph, q: ranked(ph), dc), None),
    }
    VALUES["rerank"] = {k: v for k, v in rows.items()}
    body = [[k] + [f(x, pct=True) for x in v] for k, v in rows.items()]
    body += ["\\midrule", ["GPT-4o, published", "59.6", "--", "--"], ["VILA-40B, published", "52.8", "--", "--"],
             ["D\\&C, GPT-4.1, published", "--", "64.0", "--"], ["\\quad + sub-questions, web", "--", "66.9", "--"]]
    write_table("rerank", tabular("lccc", ["& Test & Without & Validation \\\\", "Ranking & (160) & Species (154) & (40) \\\\"], body),
                "INQUIRE-Rerank: AP over the 100 fixed candidates. Jev and Clef-Flash answer the seven questions, fused with the "
                "lowercased SigLIP2 score. The middle column is the subset of test queries outside the Species supercategory "
                "used by Divide and Conquer (D\\&C). Validation queries were run with the query as written; Clef-Flash was run "
                "on the test queries only.")


def fullrank() -> None:
    """INQUIRE-Fullrank: mAP@50 for both pools, both splits, with the ceiling of perfect reranking and the pool's reach."""
    rows = []
    for pool, pname in (("vith_lc", "CLIP ViT-H"), ("siglip2_lc", "SigLIP2")):
        for split in ("test", "val"):
            Q, P = load(f"inquire_full_{pool}_{split}")
            clef = None
            if split == "test":
                Qc, Pc = load(f"inquire_full_{pool}_test", answers_dir="clef_flash")
                clef = float(np.mean([ap_at(ranked([p for p in Pc[q] if p.search_rank <= 100]), relevant(Qc[q]), 50) for q in sorted(Pc)]))
            search = float(np.mean([ap_at(search_order(P[q]), relevant(Q[q]), 50) for q in sorted(P)]))
            jev, perfect, reach = [], [], []
            for k in N.KS:
                ap, pf, rc = [], [], []
                for q in sorted(P):
                    rel = relevant(Q[q]); ph = [p for p in P[q] if p.search_rank <= k]
                    ap.append(ap_at(ranked(ph), rel, 50))
                    n_in = sum(p.image_id in rel for p in ph)
                    pf.append(min(n_in, 50) / min(len(rel), 50) if rel else 0.0)
                    rc.append(n_in / len(rel) if rel else 0.0)
                jev.append(float(np.mean(ap))); perfect.append(float(np.mean(pf))); reach.append(float(np.mean(rc)))
            VALUES[f"fullrank.{pool}.{split}"] = dict(search=search, jev=jev, clef100=clef, perfect=perfect, reach=reach, n=len(P))
            rows.append([f"{pname}, {'test' if split == 'test' else 'validation'} ({len(P)})", f(search, pct=True)]
                        + [f(x, pct=True) for x in jev] + [f(clef, pct=True)] + [f(x, pct=True) for x in perfect] + [f(x, pct=True) for x in reach])
    header = ["& Search & \\multicolumn{3}{c}{Jev + search} & Clef-Flash & \\multicolumn{3}{c}{Perfect reranking} & \\multicolumn{3}{c}{Relevant in reach (\\%)} \\\\",
              "\\cmidrule(lr){3-5}\\cmidrule(lr){6-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-12}",
              "Pool, split & alone & 100 & 200 & 500 & 100 & 100 & 200 & 500 & 100 & 200 & 500 \\\\"]
    write_table("fullrank", tabular("l" + "c" * 11, header, rows),
                "INQUIRE-Fullrank: mAP@50 when the verifier checks the pool's top 100, 200 or 500, with the pool encoder's own "
                "similarity as the search score. Perfect reranking puts every relevant photo of the checked set first; "
                "``relevant in reach'' is the share of each query's relevant photos inside the checked set. GPT-4o reranking "
                "CLIP ViT-H's top 100 reaches 43.7 on test (as published).", star=True, size="\\footnotesize")


def docci() -> None:
    """DOCCI: R@1 by description length, search alone, Jev and Clef-Flash; held out."""
    tg = {r["query_id"]: r["n_sentences"] for r in pq.read_table(data_root() / "docci/targets.parquet").to_pylist()}
    rows, vals = [], {}
    for lv in LEVELS:
        Q, P = load(f"docci_{lv}")
        Qc, Pc = load(f"docci_{lv}", answers_dir="clef_flash")
        qs = sorted(P)
        inpool = np.mean([any(p.image_id in relevant(Q[q]) for p in P[q]) for q in qs])
        s1 = np.mean([search_order(P[q])[0] in relevant(Q[q]) for q in qs])
        j1 = np.mean([ranked(P[q])[0] in relevant(Q[q]) for q in qs])
        c1 = np.mean([ranked(Pc[q])[0] in relevant(Qc[q]) for q in sorted(Pc)])
        sent = np.mean([min(int(lv[1]), tg[q]) if lv != "all" else tg[q] for q in qs])
        vals[lv] = dict(sentences=float(sent), in_pool=float(inpool), search=float(s1), jev=float(j1), clef=float(c1))
        rows.append([LEVEL_NAME[lv], f(sent, 2), f(inpool, pct=True), f(s1, pct=True), f(j1, pct=True), f(c1, pct=True)])
    Q, P = load("docci_heldout")
    qs = sorted(P)
    inpool = np.mean([any(p.image_id in relevant(Q[q]) for p in P[q]) for q in qs])
    s1 = np.mean([search_order(P[q])[0] in relevant(Q[q]) for q in qs])
    j1 = np.mean([ranked(P[q])[0] in relevant(Q[q]) for q in qs])
    vals["heldout"] = dict(in_pool=float(inpool), search=float(s1), jev=float(j1))
    rows += ["\\midrule", ["Held out, full description (200 photos)", "--", f(inpool, pct=True), f(s1, pct=True), f(j1, pct=True), "--"]]
    VALUES["docci"] = vals
    write_table("docci", tabular("lccccc", ["Query & Sentences & Target in pool & Search & Jev + search & Clef-Flash + search \\\\"], rows),
                "DOCCI: exact-target accuracy (R@1, \\%) on 500 test descriptions, with SigLIP2's top 100 checked. ``Target "
                "in pool'' is the share of queries whose target is among the photos checked. Held out: 500 other descriptions, "
                "the whole text as one query (SigLIP2 reads its first 64 tokens), 200 photos checked.", star=True)


