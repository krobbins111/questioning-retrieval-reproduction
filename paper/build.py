def respond() -> None:
    T, ok, ld, eok, eld = N.level_arrays()
    _, okc, ldc, _, _ = N.level_arrays(answers_dir="clef_flash")
    tg = {r["query_id"]: r["n_sentences"] for r in pq.read_table(data_root() / "docci/targets.parquet").to_pylist()}
    used = {lv: np.array([min(int(lv[1]), tg[t]) if lv != "all" else tg[t] for t in T], float) for lv in LEVELS}
    rows, vals = [], {}
    for lv in LEVELS:
        vals[f"fixed.{lv}"] = dict(r1=float(ok[lv].mean()), sentences=float(used[lv].mean()), photos=100)
        rows.append([f"Fixed: {LEVEL_NAME[lv].lower()}", "Jev + SigLIP2", f(ok[lv].mean(), pct=True), f(used[lv].mean(), 2), "100"])
    rows.append("\\midrule")

    def adaptive(L, O):
        a = ask_until_sure(L, O, used, list(LEVELS))
        photos = []
        for tune, test in halves(len(T)):
            tau = tau_for(np.concatenate([L[lv][tune] for lv in LEVELS]), np.concatenate([O[lv][tune] for lv in LEVELS]))
            for i in test:
                photos.append(100 * next((j + 1 for j, lv in enumerate(LEVELS) if L[lv][i] >= tau), len(LEVELS)))
        return a["exact"], a["sentences"], float(np.mean(photos))

    for name, scorer, (L, O) in (("Margin threshold", "SigLIP2", (eld, eok)), ("Margin threshold", "Jev + SigLIP2", (ld, ok)),
                                  ("Margin threshold", "Clef-Flash + SigLIP2", (ldc, okc))):
        r1, sent, ph = adaptive(L, O)
        vals[f"adaptive.{scorer}"] = dict(r1=r1, sentences=sent, photos=ph)
        rows.append([f"Adaptive: {name.lower()}", scorer, f(r1, pct=True), f(sent, 2), f(ph, 0)])
    ex = expand_rows(T, ok, ld, tg)
    vals["adaptive.expand"] = ex
    rows.append(["Adaptive: expand before asking", "Jev + SigLIP2", f(ex["r1"], pct=True), f(ex["sentences"], 2), f(ex["photos"], 0)])
    VALUES["respond"] = vals
    write_table("respond", tabular("llccc", ["Policy & Ranking score & R@1 (\\%) & Mean sentences & Photos checked \\\\"], rows),
                "DOCCI: accuracy and description use (500 descriptions). Adaptive policies answer at the first sentence count "
                "whose margin reaches the threshold of the score used, set on other targets; photos checked count 100 per "
                "round, since every new sentence changes the query and the photos are checked again. Fixed budgets of four "
                "sentences use all sentences of the 37 descriptions that have fewer.", star=True, size="\\footnotesize")
    loop_breakdown(T, ok, ld)


def expand_rows(T, ok, ld, tg) -> dict:
    lv4 = LEVELS[:-1]
    leadS, okS, nadd = {}, {}, {}
    for lv in lv4:
        src = f"docci_deep200_{lv}"
        Q, P = load(src)
        st = defaultdict(set)
        for r in pq.read_table(data_root() / src / "steered.parquet").to_pylist():
            st[r["query_id"]].add(r["image_id"])
        L, O, A = [], [], []
        for t in T:
            first = [p for p in P[t] if p.search_rank <= 100]
            chosen = [p for p in P[t] if p.image_id in st[t] and p.search_rank > 100]
            R = rank(first + chosen)
            L.append(lead(R)); O.append(R[0][0].image_id in relevant(Q[t])); A.append(len(chosen))
        leadS[lv], okS[lv], nadd[lv] = np.array(L), np.array(O), np.array(A, float)
    used = {lv: np.array([min(int(lv[1]), tg[t]) for t in T], float) for lv in lv4}
    used_all = np.array([tg[t] for t in T], float)
    acc, nu, ph = [], [], []
    for tune, test in halves(len(T)):
        tau = tau_for(np.concatenate([ld[lv][tune] for lv in LEVELS]), np.concatenate([ok[lv][tune] for lv in LEVELS]))
        done = np.zeros(len(test), bool); right = np.zeros(len(test), bool); u = np.zeros(len(test)); photos = np.zeros(len(test))
        for lv in lv4:
            act = ~done; photos[act] += 100
            s = (ld[lv][test] >= tau) & act
            right[s] = ok[lv][test][s]; u[s] = used[lv][test][s]; done |= s
            act = ~done; photos[act] += nadd[lv][test][act]
            s = (leadS[lv][test] >= tau) & act
            right[s] = okS[lv][test][s]; u[s] = used[lv][test][s]; done |= s
        rest = ~done
        photos[rest] += 100; right[rest] = ok["all"][test][rest]; u[rest] = used_all[test][rest]
        acc.append(right.mean()); nu.append(u.mean()); ph.append(photos.mean())
    return dict(r1=float(np.mean(acc)), sentences=float(np.mean(nu)), photos=float(np.mean(ph)))


def loop_breakdown(T, ok, ld) -> None:
    cnt = {lv: np.zeros(4) for lv in LEVELS}           # crossed, crossed wrong, ran out, ran out wrong (per run, summed)
    runs = 0
    for tune, test in halves(len(T)):
        tau = tau_for(np.concatenate([ld[lv][tune] for lv in LEVELS]), np.concatenate([ok[lv][tune] for lv in LEVELS]))
        runs += 1
        for i in test:
            stop = next((lv for lv in LEVELS if ld[lv][i] >= tau), None)
            if stop is None:
                cnt["all"][2] += 1; cnt["all"][3] += not ok["all"][i]
            else:
                cnt[stop][0] += 1; cnt[stop][1] += not ok[stop][i]
    rows, vals = [], {}
    for lv in LEVELS:
        c = cnt[lv] / runs
        vals[lv] = [float(x) for x in c]
        rows.append([LEVEL_NAME[lv], f(c[0], 1), f(c[1], 1), f(1 - c[1] / c[0], 1, pct=True) if c[0] else "--", f(c[2], 1) if lv == "all" else "--",
                     f(c[3], 1) if lv == "all" else "--"])
    tot = sum(cnt[lv] for lv in LEVELS) / runs
    rows += ["\\midrule", ["All", f(tot[0], 1), f(tot[1], 1), f(1 - tot[1] / tot[0], 1, pct=True), f(tot[2], 1), f(tot[3], 1)]]
    VALUES["loop"] = vals
    write_table("loop", tabular("lccccc", ["& \\multicolumn{3}{c}{Margin crossed the threshold} & \\multicolumn{2}{c}{Description exhausted} \\\\",
                                           "\\cmidrule(lr){2-4}\\cmidrule(lr){5-6}",
                                           "Stopped after & Interactions & Wrong & Right (\\%) & Interactions & Wrong \\\\"], rows),
                "Where the adaptive interaction (Jev + SigLIP2) stops on DOCCI, per 250 queries: the threshold is set on one "
                "half of the targets and the interaction runs on the other, averaged over the 80 runs of Table 3's protocol.")


