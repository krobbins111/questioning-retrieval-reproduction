def _wf_arrays(photos):
    """Per photo: whole query, aggregated statements, rating (nan if missing or failed), scaled search score, rank."""
    from qr.score import statements
    H = np.array([np.nan if p.error or p.h is None else p.h for p in photos], float)
    S = np.array([np.nan if p.error else (lambda v: np.nan if v is None else v)(statements(p.s, p.w)) for p in photos], float)
    R = np.array([np.nan if p.error or p.r is None else p.r for p in photos], float)
    c = np.array([p.search_score for p in photos], float)
    C = np.full_like(c, 0.5) if c.max() - c.min() < 1e-9 else (c - c.min()) / (c.max() - c.min())
    return np.stack([H, S, R], 1), C, np.array([p.search_rank for p in photos])


def _wf_scores(A, grid):
    """f for every photo (rows) under every configuration (columns): qr.score.scores, vectorised."""
    P, C, _ = A
    W = np.array([g[:3] for g in grid]); a = np.array([g[3] for g in grid])
    present = ~np.isnan(P)
    num = np.nan_to_num(P) @ W.T; den = present.astype(float) @ W.T
    d = np.where(den > 0, num / np.where(den > 0, den, 1.0), 0.0)
    f = (1 - a)[None, :] * d + a[None, :] * C[:, None]
    return np.where(present.any(1)[:, None], f, a[None, :] * C[:, None])


def _wf_ap(A, ids, rel, k, grid):
    """AP@k of every configuration (ranked by f rounded to 9 decimals, ties by search rank)."""
    F = np.round(_wf_scores(A, grid), 9); E = A[2]; isrel = np.array([i in rel for i in ids], float)
    out = np.empty(len(grid))
    for j in range(len(grid)):
        o = np.lexsort((E, -F[:, j]))[:k]; top = isrel[o]
        out[j] = float(np.sum(np.cumsum(top) * top / np.arange(1, len(top) + 1)) / max(1, min(len(rel), k))) if rel else 0.0
    return out


def _wf_top1(A, ids, rel, grid):
    """1 if the configuration's first photo is the target."""
    F = np.round(_wf_scores(A, grid), 9); E = A[2].astype(float)
    best = np.where(F == F.max(0)[None, :], E[:, None], np.inf).argmin(0)
    return np.array([ids[i] in rel for i in best], float)


def weight_fit() -> None:
    """Are the hand-set weights of Eq. 2 any good? (w_h, w_s, w_r) on the simplex in steps of 0.1 and the search weight
    from 0 to 0.5, fitted on validation queries (on DOCCI on half of the targets) and scored on test."""
